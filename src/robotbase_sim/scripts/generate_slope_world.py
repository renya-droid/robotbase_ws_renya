#!/usr/bin/env python3
"""Generate the slope world for the Velodyne slope study.

Course along +x (robot spawns at the origin facing +x):
  flat  0 .. foot_x
  up    foot_x .. foot_x + L        (L = rise / tan(slope))
  top   plateau of plateau_len at height rise
  down  symmetric down ramp
  flat  run-out
Ramps are static boxes whose top face passes exactly through the foot/top
edges, so there is no step for the wheels.  The values are test geometry,
not a survey of a real site.

  generate_slope_world.py --slope-deg 10 --out /tmp/slope.sdf
"""

import argparse
import json
import math

WORLD_NAME = 'velodyne_slope_study'


def course(slope_deg, foot_x=4.0, rise=0.8, plateau_len=5.0, runout=6.0):
    a = math.radians(slope_deg)
    run = rise / math.tan(a)
    up0, up1 = foot_x, foot_x + run
    dn0, dn1 = up1 + plateau_len, up1 + plateau_len + run
    return {
        'slope_deg': slope_deg, 'grade_percent': round(100 * math.tan(a), 2), 'rise': rise,
        'up_start': up0, 'up_end': up1, 'down_start': dn0, 'down_end': dn1,
        'end_x': dn1 + runout,
    }


def ramp_box(name, x_top_edge_low, z_low, slope, length_xy, width, sign, thickness=3.0):
    """Box whose top face is the line from (x_low, z_low) rising (sign=+1) or falling.

    The box is thick and mostly below ground so a wheel can never end up
    closer to its bottom face than to its top face.
    """
    slant = length_xy / math.cos(slope)
    # midpoint of top face
    mx = x_top_edge_low + 0.5 * length_xy
    mz = z_low + sign * 0.5 * length_xy * math.tan(slope)
    # top face normal (x, z)
    nx, nz = -sign * math.sin(slope), math.cos(slope)
    cx, cz = mx - nx * thickness / 2, mz - nz * thickness / 2
    pitch = -sign * slope
    return box(name, cx, cz, pitch, slant, width, thickness, (0.45, 0.42, 0.38))


def box(name, x, z, pitch, sx, sy, sz, rgb):
    geom = f'<box><size>{sx:.4f} {sy:.4f} {sz:.4f}</size></box>'
    mat = (f'<material><ambient>{rgb[0]} {rgb[1]} {rgb[2]} 1</ambient>'
           f'<diffuse>{rgb[0]} {rgb[1]} {rgb[2]} 1</diffuse></material>')
    return f'''
    <model name="{name}">
      <static>true</static>
      <pose>{x:.4f} 0 {z:.4f} 0 {pitch:.6f} 0</pose>
      <link name="link">
        <collision name="collision"><geometry>{geom}</geometry>
          <surface><friction><ode><mu>1.0</mu><mu2>1.0</mu2></ode></friction></surface>
        </collision>
        <visual name="visual"><geometry>{geom}</geometry>{mat}</visual>
      </link>
    </model>'''


def build(slope_deg, width=6.0):
    c = course(slope_deg)
    a = math.radians(slope_deg)
    run = c['up_end'] - c['up_start']
    plateau = c['down_start'] - c['up_end']
    parts = [
        ramp_box('ramp_up', c['up_start'], 0.0, a, run, width, +1),
        box('plateau', c['up_end'] + plateau / 2, c['rise'] / 2, 0.0, plateau, width, c['rise'],
            (0.50, 0.47, 0.42)),
        ramp_box('ramp_down', c['down_start'], c['rise'], a, run, width, -1),
    ]
    sdf = f'''<?xml version="1.0"?>
<!-- generated by generate_slope_world.py: {json.dumps(c)} -->
<sdf version="1.9">
  <world name="{WORLD_NAME}">
    <physics name="1ms" type="ignored">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <light type="directional" name="sun">
      <pose>0 0 10 0 0 0</pose>
      <cast_shadows>false</cast_shadows>
      <diffuse>0.9 0.9 0.9 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.5 0.2 -0.9</direction>
    </light>
    <model name="ground">
      <static>true</static>
      <link name="link">
        <collision name="collision"><geometry><plane><normal>0 0 1</normal><size>200 200</size></plane></geometry>
          <surface><friction><ode><mu>1.0</mu><mu2>1.0</mu2></ode></friction></surface>
        </collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>200 200</size></plane></geometry>
          <material><ambient>0.35 0.35 0.37 1</ambient><diffuse>0.40 0.40 0.42 1</diffuse></material>
        </visual>
      </link>
    </model>{''.join(parts)}
  </world>
</sdf>
'''
    return sdf, c


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--slope-deg', type=float, default=10.0)
    ap.add_argument('--out', required=True)
    args = ap.parse_args()
    sdf, c = build(args.slope_deg)
    with open(args.out, 'w', encoding='utf-8') as f:
        f.write(sdf)
    print(json.dumps(c))


if __name__ == '__main__':
    main()
